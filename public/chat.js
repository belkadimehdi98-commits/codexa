const chatBox = document.getElementById("chat-box");
const chatForm = document.getElementById("chat-form");
const userInput = document.getElementById("user-input");

// Mode buttons
const modeButtons = document.querySelectorAll(".mode-btn");
let currentMode = "chat"; // default mode

modeButtons.forEach(btn => {
  btn.addEventListener("click", () => {
    modeButtons.forEach(b => b.classList.remove("active"));
    btn.classList.add("active");
    currentMode = btn.dataset.mode;
  });
});

// Add message to chat
function addMessage(sender, content, isCode = false, isImage = false) {
  const msg = document.createElement("div");
  msg.classList.add("message", sender);

  if (isCode) {
    // Code block
    const pre = document.createElement("pre");
    const code = document.createElement("code");
    code.textContent = content;
    pre.appendChild(code);
    msg.appendChild(pre);

    // Copy & Download buttons
    const actions = document.createElement("div");
    actions.classList.add("code-actions");

    const copyBtn = document.createElement("button");
    copyBtn.classList.add("copy-btn");
    copyBtn.textContent = "Copy";
    copyBtn.onclick = () => {
      navigator.clipboard.writeText(content);
      copyBtn.textContent = "Copied!";
      setTimeout(() => (copyBtn.textContent = "Copy"), 1500);
    };

    const downloadBtn = document.createElement("button");
    downloadBtn.classList.add("download-btn");
    downloadBtn.textContent = "Download";
    downloadBtn.onclick = () => {
      const blob = new Blob([content], { type: "text/plain" });
      const url = URL.createObjectURL(blob);
      const a = document.createElement("a");
      a.href = url;
      a.download = "codexa-code.txt";
      a.click();
      URL.revokeObjectURL(url);
    };

    actions.appendChild(copyBtn);
    actions.appendChild(downloadBtn);
    msg.appendChild(actions);
  } else if (isImage) {
    // Image block
    const img = document.createElement("img");
    img.src = content;
    img.alt = "Generated by Codexa";
    img.classList.add("generated-img");
    msg.appendChild(img);

    const downloadBtn = document.createElement("button");
    downloadBtn.classList.add("download-btn");
    downloadBtn.textContent = "Download Image";
    downloadBtn.onclick = () => {
      const a = document.createElement("a");
      a.href = content;
      a.download = "codexa-image.png";
      a.click();
    };
    msg.appendChild(downloadBtn);
  } else {
    msg.textContent = content;
  }

  chatBox.appendChild(msg);
  chatBox.scrollTop = chatBox.scrollHeight; // auto-scroll inside chat box
}

// Handle form submit
chatForm.addEventListener("submit", async (e) => {
  e.preventDefault();
  const input = userInput.value.trim();
  if (!input) return;

  addMessage("user", input);
  userInput.value = "";

  // Loading message
  const loading = document.createElement("div");
  loading.classList.add("message", "bot");
  loading.textContent = "⏳ Codexa is thinking...";
  chatBox.appendChild(loading);
  chatBox.scrollTop = chatBox.scrollHeight;

  try {
    const res = await fetch("/api/chat", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message: input, mode: currentMode }),
    });
    const data = await res.json();
    loading.remove();

    if (currentMode === "code") {
      addMessage("bot", data.reply, true, false);
    } else if (currentMode === "image") {
      addMessage("bot", data.imageUrl, false, true);
    } else {
      addMessage("bot", data.reply);
    }
  } catch (err) {
    loading.remove();
    addMessage("bot", "❌ Error: " + err.message);
  }
});
